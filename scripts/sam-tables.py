"""SAM's tables (the micro:bit firmware's lib/sam/*Tabs.h, micropython-microbit-v2 v2.1.2) as src/sim/sam/tables.ts,
so the simulator's speech says what the board says. The headers are read as text; nothing of them is run.
Run: python3 scripts/sam-tables.py   (needs .cache/micropython-microbit-v2.1.2, see vendor/micropython/README.md)"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
SAM = ROOT / ".cache/micropython-microbit-v2.1.2/lib/sam"
HEADERS = ["SamTabs.h", "ReciterTabs.h", "RenderTabs.h"]


def strip_comments(text):
    out, i, n = [], 0, len(text)
    while i < n:
        if text[i] == "'":                       # a char literal: '/', '\'', '*'
            j = i + 1
            if text[j] == "\\":
                j += 1
            j += 2
            out.append(text[i:j])
            i = j
        elif text.startswith("//", i):
            i = text.index("\n", i)
        elif text.startswith("/*", i):
            i = text.index("*/", i) + 2
        else:
            out.append(text[i])
            i += 1
    return "".join(out)


def elements(body):
    """Split at commas, but not the comma in ','."""
    out, cur, i = [], "", 0
    while i < len(body):
        if body[i] == "'":
            j = i + 1
            if body[j] == "\\":
                j += 1
            j += 2
            cur += body[i:j]
            i = j
        elif body[i] == ",":
            out.append(cur)
            cur = ""
            i += 1
        else:
            cur += body[i]
            i += 1
    out.append(cur)
    return [e.strip() for e in out if e.strip()]


def value(e):
    total = 0
    for part in e.split("|"):
        part = part.strip()
        m = re.fullmatch(r"'(\\?.)'", part, re.S)
        if m:
            ch = m.group(1)
            total |= ord(ch[-1])
        else:
            total |= int(part, 0)
    assert 0 <= total <= 255, e
    return total


lines = ["// Generated by scripts/sam-tables.py from the micro:bit firmware's lib/sam/*Tabs.h — do not edit.",
         "/** SAM's tables (Software Automatic Mouth, 1982), byte for byte as micropython-microbit-v2 v2.1.2 has them. */"]
count = 0
for h in HEADERS:
    text = strip_comments((SAM / h).read_text())
    for m in re.finditer(r"const\s+(?:unsigned\s+)?char\s+(\w+)\s*\[\s*(\w*)\s*\]\s*=\s*\{(.*?)\}\s*;", text, re.S):
        name, size, body = m.group(1), m.group(2), m.group(3)
        vals = [value(e) for e in elements(body)]
        if size:
            n = int(size, 0)
            assert len(vals) <= n, name
            vals += [0] * (n - len(vals))
        rows = [", ".join(str(v) for v in vals[i:i + 24]) for i in range(0, len(vals), 24)]
        lines.append(f"/** {h}, {len(vals)} bytes. */")
        lines.append(f"export const {name} = new Uint8Array([\n  " + ",\n  ".join(rows) + ",\n]);")
        count += 1
out = ROOT / "src/sim/sam/tables.ts"
out.write_text("\n".join(lines) + "\n")
print(f"{out.relative_to(ROOT)}: {count} tables")
