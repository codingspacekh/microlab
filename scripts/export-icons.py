"""The prototype's UI icons (design/build.py ICONS) as src/renderer/ui/icon-data.ts, so the app draws the same ones.
Run: python3 scripts/export-icons.py"""
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "design"))
import build  # noqa: E402

out = ROOT / "src/renderer/ui/icon-data.ts"
lines = ["// Generated by scripts/export-icons.py from design/build.py — do not edit.",
         "/** Icon name → the SVG inside a 24 × 24 viewBox, stroked (class .ico). */",
         "export const ICONS: Record<string, string> = {"]
for name, body in sorted(build.ICONS.items()):
    lines.append(f"  {json.dumps(name)}: {json.dumps(body)},")
lines.append("};")
lines.append("/** Icons drawn filled, not stroked. */")
lines.append(f"export const FILLED = new Set({json.dumps(sorted(build.FILLED))});")
out.write_text("\n".join(lines) + "\n")
print(f"{out.relative_to(ROOT)}: {len(build.ICONS)} icons")
