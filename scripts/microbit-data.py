"""Writes src/python/microbit/_data.py — the micro:bit's font and built-in images — from the firmware sources in
.cache/ (fetch them as docs/acceptance/M2.md says):
  font:   Lancaster University's MicroBitFont (MIT), as in MicroPython's ports/nrf/boards/MICROBIT/modules/microbitfont.h
          (CODAL's BitmapFont system font on the V2 is the same font — to confirm in the golden recordings)
  images: micropython-microbit-v2 v2.1.2 src/codal_port/microbit_constimage.c (MIT)
  tunes:  micropython-microbit-v2 v2.1.2 src/codal_port/modmusictunes.c (MIT)
Run: python3 scripts/microbit-data.py
"""
import pathlib
import re

ROOT = pathlib.Path(__file__).resolve().parent.parent
FONT = ROOT / ".cache/micropython-v1.29.0/ports/nrf/boards/MICROBIT/modules/microbitfont.h"
IMAGES = ROOT / ".cache/micropython-microbit-v2.1.2/src/codal_port/microbit_constimage.c"
TUNES = ROOT / ".cache/micropython-microbit-v2.1.2/src/codal_port/modmusictunes.c"
OUT = ROOT / "src/python/microbit/_data.py"


def font() -> bytes:
    src = FONT.read_text()
    body = src[src.index("{", src.index("font_pendolino3_5x5_pad3msb")):]
    data = bytes(int(x, 16) for x in re.findall(r"0x[0-9a-fA-F]+", body))
    assert len(data) == 95 * 5, len(data)
    return data


def images() -> tuple[dict, list, list]:
    src = IMAGES.read_text()
    found = {}
    for name, bits in re.findall(r"microbit_const_image_(\w+)_obj = SMALL_IMAGE\(([^)]*)\)", src):
        values = [int(b) for b in re.findall(r"[01]", bits)]
        assert len(values) == 25, name
        found[name.upper()] = "".join("9" if v else "0" for v in values)

    def tuple_of(name):
        block = src[src.index(f"microbit_const_image_{name}_tuple_obj"):]
        block = block[:block.index("};")]
        return [n.upper() for n in re.findall(r"microbit_const_image_(\w+)_obj", block)[1:]]

    return found, tuple_of("all_clocks"), tuple_of("all_arrows")


def tunes() -> dict:
    """T(name, N(qstr), ...) -> {NAME: ('note', ...)}; a qstr's _colon_ is ':', _hash_ is '#'."""
    src = TUNES.read_text()
    out = {}
    for name, body in re.findall(r"^T\((\w+),(.*?)\);", src, re.S | re.M):
        notes = [q.replace("_colon_", ":").replace("_hash_", "#") for q in re.findall(r"N\((\w+)\)", body)]
        out[name.upper()] = tuple(notes)
    return out


def main() -> None:
    data = font()
    found, clocks, arrows = images()
    lines = [
        "# Generated by scripts/microbit-data.py — do not edit. The micro:bit's font (Lancaster University's",
        "# MicroBitFont, MIT), built-in images and tunes (micropython-microbit-v2 v2.1.2, MIT).",
        "",
        "# 5 bytes per character, ASCII 32-126; in each byte (a row) bit 4 is the leftmost column",
        "FONT = (",
    ]
    for i in range(0, len(data), 20):
        lines.append("    b'" + "".join(f"\\x{b:02x}" for b in data[i:i + 20]) + "'")
    lines.append(")")
    lines.append("")
    lines.append("# name -> 25 brightnesses, row by row (0 or 9)")
    lines.append("IMAGES = {")
    for name, pixels in found.items():
        lines.append(f"    '{name}': '{pixels}',")
    lines.append("}")
    lines.append(f"ALL_CLOCKS = {tuple(clocks)!r}")
    lines.append(f"ALL_ARROWS = {tuple(arrows)!r}")
    lines.append("")
    lines.append("# music's built-in tunes")
    lines.append("TUNES = {")
    for name, notes in tunes().items():
        lines.append(f"    '{name}': {notes!r},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"{OUT.relative_to(ROOT)}: {len(data)} font bytes, {len(found)} images, {len(clocks)} clocks, {len(arrows)} arrows, {len(tunes())} tunes")


if __name__ == "__main__":
    main()
